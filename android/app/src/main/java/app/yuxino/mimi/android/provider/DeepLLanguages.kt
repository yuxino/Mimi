internal fun deepLLanguage(code: String, source: Boolean, compatible: Boolean = false): String {
    val codes = if (compatible) { if (source) DEEPLX_SOURCE_CODES else DEEPLX_TARGET_CODES }
        else { if (source) DEEPL_SOURCE_CODES else DEEPL_TARGET_CODES }
    require(code in codes) { "translation_language" }
    return when (code) {
        "no" -> "NB"
        "zh_tw" -> "ZH-HANT"
        else -> code.uppercase(java.util.Locale.ROOT)
    }
}
